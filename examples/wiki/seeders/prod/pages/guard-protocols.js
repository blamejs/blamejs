  "<h2 id=\"guard-graphql-threat-catalog\">Threat catalog <a class=\"anchor\" href=\"#guard-graphql-threat-catalog\">#</a></h2>",
  "<ul>",
  "<li><strong>Query depth bombs</strong> — deeply-nested selection sets multiply N² against schema depth, bypassing field-level rate limits. Caps at strict 8 / balanced 12 / permissive 24.</li>",
  "<li><strong>Alias-bomb breadth DoS</strong> — same field repeated under different aliases (<code>a:friend b:friend c:friend</code>) bypasses per-field limits.</li>",
  "<li><strong>Introspection</strong> — <code>__schema</code> / <code>__type</code> queries leak schema details in production.</li>",
  "<li><strong>Batch query DoS</strong> — operators supporting <code>[{},{}]</code> batch arrays get N requests for one HTTP hit.</li>",
  "<li><strong>Persisted-query enforcement</strong> — when <code>persistedQueryPolicy: \"require\"</code>, refuse free-form queries that don't carry an <code>extensions.persistedQuery.sha256Hash</code>.</li>",
  "<li><strong>Operation-name allowlist</strong> — operator may pin <code>operationName</code> to a whitelist of named operations.</li>",
  "<li><strong>Variable type confusion</strong> — variables passed as the wrong shape (string for ID expecting Int, object for scalar). Operator declares <code>variableShapes: { id: \"string\", limit: \"number\" }</code>; the guard refuses non-shape-matching types.</li>",
